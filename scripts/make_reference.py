"""Regenerate the reference states in tests/test_sgp4.cpp.

Uses the `sgp4` Python package (Vallado's reference implementation; WGS-72,
improved mode), which is what this C++ SGP4 is checked against.

    pip install sgp4
    python scripts/make_reference.py > tests/reference_states.inc
"""
from sgp4.api import Satrec

TLES = [
    ("ISS",
     "1 25544U 98067A   24001.50000000  .00016717  00000-0  10270-3 0  9025",
     "2 25544  51.6400 208.9163 0006703 296.7361  63.2861 15.49560921426457"),
    ("SPACETRACK-88888",
     "1 88888U          80275.98708465  .00073094  13844-3  66816-4 0    87",
     "2 88888  72.8435 115.9689 0086731  52.6988 110.5714 16.05824518  1058"),
    ("ECCENTRIC",
     "1 22222U 95001A   24001.50000000  .00000500  00000-0  20000-4 0  9998",
     "2 22222  63.4000 150.0000 1800000 270.0000  30.0000  9.50000000 50001"),
]
TIMES = [0.0, 360.0, 1440.0, 4320.0]

print("// Generated by scripts/make_reference.py with the sgp4 Python package")
print("// {name, line1, line2, tsince [min], x, y, z [km], vx, vy, vz [km/s]}")
for name, l1, l2 in TLES:
    sat = Satrec.twoline2rv(l1, l2)
    for t in TIMES:
        err, r, v = sat.sgp4_tsince(t)
        assert err == 0
        print(f'{{"{name}", "{l1}", "{l2}", {t:.1f}, '
              f'{r[0]:.9f}, {r[1]:.9f}, {r[2]:.9f}, {v[0]:.12f}, {v[1]:.12f}, {v[2]:.12f}}},')
